#!/usr/bin/env python3
"""Build/check a complete, evidence-linked capability record from the research inventory.

This checks references and completeness. It does not infer conformance from test names or
replace the execution results in docs/styling/validation.md. It never executes evidence text.
"""
from __future__ import annotations
import argparse
import collections
import json
import re
import shlex
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "docs/styling"


def ordered_unique(values):
    return list(dict.fromkeys(values))


def render(records, inventory):
    counts = collections.Counter(item["phase"] for item in inventory)
    lines = [
        "# Styling capability coverage",
        "",
        "This is the implementation record for every group in the original research inventory. "
        "**A covered group means the stated profile has real consumers and named evidence; it does not mean every CSS/SVG interpretation or every native platform is supported.** "
        "Read the limitations with the profile. Execution results and skipped platform cases are in [validation.md](validation.md).",
        "",
        f"Coverage: **{len(records)} / {len(inventory)} groups**, "
        f"**{sum(len(item['options']) for item in inventory)} researched option mentions**, "
        f"**{len(set(item['category'] for item in inventory))} categories**. "
        "Option mentions overlap and are not a count of independent implemented properties.",
        "",
        "| Plan phase | Groups |",
        "|---|---:|",
    ]
    lines += [f"| {phase} | {count} |" for phase, count in sorted(counts.items())]
    lines += ["", "Generated by `python3 tools/styling/coverage.py`. "
              "The [machine-readable record](coverage.json) retains all original option lists and acceptance statements.", ""]
    category = None
    for row in records:
        if row["category"] != category:
            category = row["category"]
            lines += [f"## {category}", ""]
        lines += [f"### {row['id']} — {row['title']}", "", f"**{row['phase']} · Implemented profile**", ""]
        lines += [p + "\n" for p in row["profiles"]]
        links = [f"[{path}](../../{path})" for path in row["implementation"]]
        lines += ["Implementation: " + ", ".join(links) + ".", "", "Evidence:", ""]
        lines += [f"- `{name}`" for name in row["verification"]]
        lines += ["", "Profile boundaries:", ""]
        lines += [f"- {limit}" for limit in row["limitations"]] or ["- No additional restriction beyond the public operation's validated inputs and explicit storage capacities."]
        lines += [""]
    return "\n".join(lines)


def collect():
    inventory_doc = json.loads((ROOT / "docs/research/styling/inventory.json").read_text())
    inventory = inventory_doc["items"]
    ids = {item["id"] for item in inventory}
    tests = set()
    for path in (ROOT / "src").rglob("*.zig"):
        tests.update(re.findall(r'^test "([^"\n]+)"', path.read_text(), re.M))
    evidence = collections.defaultdict(list)
    for path in sorted(DEST.glob("*-evidence.json")):
        seen = set()
        for row in json.loads(path.read_text()):
            identity = row["id"]
            if identity not in ids:
                raise ValueError(f"{path.name}: unknown inventory ID {identity}")
            if identity in seen:
                raise ValueError(f"{path.name}: duplicate ID {identity}")
            seen.add(identity)
            if not row["implementation"] or not row["verification"] or not row["profile"].strip():
                raise ValueError(f"{path.name}: empty implementation, evidence or profile for {identity}")
            for source in row["implementation"]:
                target = (ROOT / source).resolve()
                if not target.is_relative_to(ROOT) or not target.is_file():
                    raise ValueError(f"{identity}: missing or outside-repository path {source}")
            for verification in row["verification"]:
                if verification in tests:
                    continue
                command = shlex.split(verification)
                if command and command[0] in {"python", "python3", "node"} and len(command) > 1 and (ROOT / command[1]).is_file():
                    continue
                raise ValueError(f"{identity}: unknown test or fixture-generator reference {verification!r}")
            evidence[identity].append((path.name, row))
    missing = ids - evidence.keys()
    if missing:
        raise ValueError("Missing inventory groups: " + ", ".join(sorted(missing)))
    records = []
    for item in inventory:
        entries = evidence[item["id"]]
        records.append({
            "id": item["id"], "category": item["category"], "title": item["title"], "phase": item["phase"],
            "coverage": "implemented_profile", "research_options": item["options"], "research_acceptance": item["acceptance"],
            "profiles": ordered_unique(row["profile"] for _, row in entries),
            "implementation": ordered_unique(value for _, row in entries for value in row["implementation"]),
            "verification": ordered_unique(value for _, row in entries for value in row["verification"]),
            "limitations": ordered_unique(value for _, row in entries for value in row["limitations"]),
            "evidence_files": [name for name, _ in entries],
        })
    document = {"schema_version": 1, "baseline_commit": inventory_doc["baseline_commit"],
                "meaning": "Implemented within the stated profile; not universal standards or platform conformance.", "items": records}
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n", render(records, inventory), len(records)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate references and fail if generated coverage is stale")
    args = parser.parse_args()
    try:
        json_text, markdown, count = collect()
        for name, data in (("coverage.json", json_text), ("coverage.md", markdown)):
            path = DEST / name
            if args.check:
                if not path.exists() or path.read_text() != data:
                    raise ValueError(f"{path.relative_to(ROOT)} is missing/stale; run tools/styling/coverage.py")
            else:
                path.write_text(data)
        print(f"Validated {count} capability groups, implementation paths and named evidence.")
    except (ValueError, KeyError, TypeError) as exc:
        parser.exit(1, f"coverage: {exc}\n")


if __name__ == "__main__":
    main()
