"""API index of the lcgr package, generated from the sources (`zig build docs`).

A port of prototype/mkindex.py: the same line scanner, run over every file src/lcgr.zig exports,
in export order. Usage: apiindex.py <src/lcgr.zig> <out.md>
"""
import os, re, sys

KW = ('pub', 'const', 'var', 'fn', 'test', 'comptime', 'inline', 'return', 'if', 'for', 'while', 'switch', 'else', 'defer', 'try', '_')
LAYOUT = r'(?:extern |packed |bitpack )?'


def clean(raw):
    c = re.sub(r'"(\\.|[^"\\])*"', '""', raw)
    c = re.sub(r"'(\\.|[^'\\])'", "''", c)
    return c.split('//')[0]


def sentence(doc):
    return re.split(r'(?<=\.)\s', ' '.join(doc))[0] if doc else ''


def index(path):
    lines = open(path).read().split('\n')
    cont = {}; order = []

    def get(p, kind='', doc=''):
        k = '.'.join(x for x in p if x)
        if k not in cont:
            cont[k] = {'kind': kind, 'doc': doc, 'fields': [], 'consts': [], 'fns': []}; order.append(k)
        return cont[k]

    get([], 'file')
    header = [s.strip()[3:].strip() for s in lines if s.startswith('//!')]
    stack = []; depth = 0; doc = []
    for raw in lines:
        s = raw.strip()
        if s.startswith('\\\\') or s.startswith('//!'): continue
        if s.startswith('///'): doc.append(s[3:].strip()); continue
        if s.startswith('//') or s == '':
            if s.startswith('//'): doc = []
            continue
        code = clean(raw)
        opened = code.count('{'); closed = code.count('}')
        path = [n for n, _, _ in stack]
        vis = all(p for _, _, p in stack)
        member = (depth == (stack[-1][1] + 1 if stack else 0))
        first = sentence(doc)
        m = re.match(r'\s*(pub )?const (\w+)(?:: [^=]+)? = ' + LAYOUT + r'(struct|enum|union)\b', code)
        g = re.match(r'\s*(pub )?fn (\w+)\((.*)\) type \{', code)
        r = re.match(r'\s*return ' + LAYOUT + r'struct \{', code)
        if m and opened > closed:
            if m.group(1) and vis and member: get(path + [m.group(2)], m.group(3), first)
            stack.append((m.group(2), depth, bool(m.group(1)) and member))
        elif g and opened > closed:
            if g.group(1) and vis and member:
                get(path, '')['fns'].append((f"fn {g.group(2)}({g.group(3)}) type", first))
                get(path + [g.group(2) + '(..)'], 'generic struct', first)
            stack.append((g.group(2) + '(..)', depth, bool(g.group(1)) and member))
        elif r and opened > closed:
            stack.append(('', depth, True))
        elif vis and member:
            f = re.match(r'\s*pub (?:inline )?fn (\w+)\((.*)\) (.+?) \{\s*$', raw)
            c = re.match(r'\s*pub const (\w+)(: [^=]+)? = (.+);\s*$', raw)
            fld = re.match(r'\s*([a-z_]\w*): ', code)
            if f: get(path)['fns'].append((f"fn {f.group(1)}({f.group(2)}) {f.group(3)}", first))
            elif c: get(path)['consts'].append((f"{c.group(1)}{c.group(2) or ''} = {c.group(3)}", first))
            elif fld and fld.group(1) not in KW and stack: get(path)['fields'].append(fld.group(1))
        depth += opened - closed
        while stack and depth <= stack[-1][1]: stack.pop()
        doc = []
    return sentence(header), cont, order


def main(root, out):
    exports = re.findall(r'^pub const (\w+) = @import\("([^"]+\.zig)"\);', open(root).read(), re.M)
    md = ["# API index", "",
          "Generated by `zig build docs` from the files `src/lcgr.zig` exports, in export order: every public type with its fields, "
          "and every public function and constant with the first sentence of its doc comment. The sources are the definitions; this is the map.", ""]
    total = 0
    for name, rel in exports:
        header, cont, order = index(os.path.join(os.path.dirname(root), rel))
        md += [f"## `lcgr.{name}` (src/{rel})", ""]
        if header: md += [header, ""]
        for k in order:
            c = cont[k]
            if not (c['fields'] or c['consts'] or c['fns'] or c['doc']): continue
            md.append(f"### `{k}` ({c['kind']})" if k else "### Top level")
            if c['doc']: md.append(c['doc'])
            md.append("")
            if c['fields']: md.append("Fields: " + ", ".join(f"`{x}`" for x in c['fields'])); md.append("")
            for sig, doc in c['consts'] + c['fns']:
                total += 1
                sig = sig if len(sig) < 160 else sig[:157] + '…'
                md.append(f"- `{sig}`" + (f": {doc}" if doc else ""))
            md.append("")
    open(out, "w").write('\n'.join(md))
    print(f"API index: {len(exports)} files, {len(md)} lines, {total} functions and constants", file=sys.stderr)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
