//! Build-time host tool, not part of the package: reads the UCD files in `data/` and writes the
//! Zig source of the `unicode_tables` module that property.zig looks up. build.zig runs it.
//!
//!   gen <out.zig> GraphemeBreakProperty emoji-data DerivedCoreProperties WordBreakProperty
//!       LineBreak EastAsianWidth DerivedGeneralCategory DerivedBidiClass BidiBrackets Scripts
//!
//! Every table is one value per code point, emitted run-length encoded: `<name>_start` holds the
//! first code point of each run, `<name>_value` its value.

const std = @import("std");
const property = @import("property.zig");

const n_cp = 0x110000;

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const gpa = init.arena.allocator();
    var args = try init.minimal.args.iterateAllocator(gpa);
    _ = args.next();
    const out_path = args.next().?;
    var text: [10][]const u8 = undefined;
    for (&text) |*t| t.* = try std.Io.Dir.cwd().readFileAlloc(io, args.next().?, gpa, .limited(8 << 20));
    const gbp, const emoji, const dcp, const wbp, const lbt, const eaw, const gct, const bidit, const brackets, const scripts = text;

    const gcb = try fill(gpa, gbp, null, property.Gcb, .Other);
    const incb = try fill(gpa, dcp, "InCB", property.InCB, .None);
    const pict = try fill(gpa, emoji, "Extended_Pictographic", Present, .no);
    const wb = try fill(gpa, wbp, null, property.Wb, .Other);
    const lb = try fill(gpa, lbt, null, property.Lb, .XX);
    const ea = try fill(gpa, eaw, null, Eaw, .N);
    const gc = try fill(gpa, gct, null, Gc, .Cn);
    const bidi = try fill(gpa, bidit, null, property.BidiClass, .L);

    // Script names are not fixed by property.zig: the enum is generated in order of appearance.
    var names: std.ArrayList([]const u8) = .empty;
    try names.append(gpa, "Unknown");
    const script = try gpa.alloc(u8, n_cp);
    @memset(script, 0);
    var it = Lines{ .text = scripts };
    while (it.next()) |e| {
        const name = e.fields[0];
        const id = for (names.items, 0..) |s, i| {
            if (std.mem.eql(u8, s, name)) break i;
        } else blk: {
            try names.append(gpa, name);
            break :blk names.items.len - 1;
        };
        @memset(script[e.lo .. @as(usize, e.hi) + 1], @intCast(id));
    }

    const grapheme = try gpa.alloc(u8, n_cp);
    const word = try gpa.alloc(u8, n_cp);
    const line = try gpa.alloc(u16, n_cp);
    for (0..n_cp) |cp| {
        const g: property.Gcb = @fromBackingInt(@intCast(gcb[cp]));
        const p = pict[cp] != 0;
        const c: Gc = @fromBackingInt(@intCast(gc[cp]));
        const e: Eaw = @fromBackingInt(@intCast(ea[cp]));
        grapheme[cp] = @bitCast(property.Grapheme{ .gcb = g, .incb = @fromBackingInt(@intCast(incb[cp])), .ext_pict = p });
        word[cp] = @bitCast(property.Word{ .wb = @fromBackingInt(@intCast(wb[cp])), .ext_pict = p });
        line[cp] = @bitCast(property.Line{
            .lb = @fromBackingInt(@intCast(lb[cp])),
            .east_asian = e == .F or e == .W or e == .H,
            .pict_cn = p and c == .Cn,
            .pi = c == .Pi,
            .pf = c == .Pf,
            .mark = c == .Mn or c == .Mc,
        });
    }

    var aw: std.Io.Writer.Allocating = .init(gpa);
    const w = &aw.writer;
    try w.writeAll("//! Generated by src/text/unicode/gen.zig from the UCD 16.0.0 files. Do not edit.\n\n");
    try w.writeAll("pub const Script = enum(u8) {");
    for (names.items) |s| try w.print(" {s},", .{s});
    try w.writeAll(" };\n");
    try emit(w, "grapheme", u8, grapheme);
    try emit(w, "word", u8, word);
    try emit(w, "line", u16, line);
    try emit(w, "bidi", u8, bidi);
    try emit(w, "script", u8, script);

    var bit = Lines{ .text = brackets };
    var bcp: std.ArrayList(u8) = .empty;
    var bpair: std.ArrayList(u8) = .empty;
    var bopen: std.ArrayList(u8) = .empty;
    var count: usize = 0;
    while (bit.next()) |e| : (count += 1) {
        try appendPrint(gpa, &bcp, "0x{X},", .{e.lo});
        try appendPrint(gpa, &bpair, "0x{s},", .{e.fields[0]});
        try appendPrint(gpa, &bopen, "{},", .{e.fields[1][0] == 'o'});
    }
    try w.print("pub const bracket_cp = [{d}]u21{{{s}}};\n", .{ count, bcp.items });
    try w.print("pub const bracket_pair = [{d}]u21{{{s}}};\n", .{ count, bpair.items });
    try w.print("pub const bracket_open = [{d}]bool{{{s}}};\n", .{ count, bopen.items });

    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = out_path, .data = aw.written() });
}

fn appendPrint(gpa: std.mem.Allocator, list: *std.ArrayList(u8), comptime fmt: []const u8, args: anytype) !void {
    var buf: [64]u8 = undefined;
    try list.appendSlice(gpa, try std.fmt.bufPrint(&buf, fmt, args));
}

const Present = enum(u8) { no, Extended_Pictographic };
const Eaw = enum(u8) { N, A, F, H, Na, W };
const Gc = enum(u8) { Cn, Lu, Ll, Lt, Lm, Lo, Mn, Mc, Me, Nd, Nl, No, Pc, Pd, Ps, Pe, Pi, Pf, Po, Sm, Sc, Sk, So, Zs, Zl, Zp, Cc, Cf, Cs, Co };

/// One value per code point from a UCD property file. `prop` selects the lines of a
/// multi-property file (`cp ; InCB ; Linker`); without it the first field is the value.
/// `@missing` lines set defaults; they precede the data in every file used here.
fn fill(gpa: std.mem.Allocator, text: []const u8, comptime prop: ?[]const u8, comptime E: type, default: E) ![]u8 {
    const out = try gpa.alloc(u8, n_cp);
    @memset(out, @backingInt(default));
    var it = Lines{ .text = text };
    while (it.next()) |e| {
        const value = if (prop) |p| blk: {
            if (!std.mem.eql(u8, e.fields[0], p)) continue;
            break :blk if (E == Present) "Extended_Pictographic" else e.fields[1];
        } else e.fields[0];
        const v = std.meta.stringToEnum(E, value) orelse longBidi(E, value) orelse {
            std.debug.print("gen: unknown value '{s}' for {s}\n", .{ value, @typeName(E) });
            return error.UnknownValue;
        };
        @memset(out[e.lo .. @as(usize, e.hi) + 1], @backingInt(v));
    }
    return out;
}

/// DerivedBidiClass.txt writes its @missing defaults with long names.
fn longBidi(comptime E: type, name: []const u8) ?E {
    if (E != property.BidiClass) return null;
    const long = [_]struct { []const u8, property.BidiClass }{
        .{ "Left_To_Right", .L }, .{ "Right_To_Left", .R }, .{ "Arabic_Letter", .AL }, .{ "European_Terminator", .ET },
    };
    for (long) |l| if (std.mem.eql(u8, l[0], name)) return l[1];
    return null;
}

/// Data lines and `# @missing:` lines of a UCD file: a code point range and up to two fields.
const Lines = struct {
    text: []const u8,
    pos: usize = 0,

    const Entry = struct { lo: u21, hi: u21, fields: [2][]const u8 };

    fn next(it: *Lines) ?Entry {
        while (it.pos < it.text.len) {
            const end = std.mem.indexOfScalarPos(u8, it.text, it.pos, '\n') orelse it.text.len;
            var ln = it.text[it.pos..end];
            it.pos = end + 1;
            const missing = "# @missing:";
            if (std.mem.startsWith(u8, ln, missing)) ln = ln[missing.len..];
            if (std.mem.indexOfScalar(u8, ln, '#')) |h| ln = ln[0..h];
            ln = std.mem.trim(u8, ln, " \t\r");
            if (ln.len == 0) continue;
            var f = std.mem.splitScalar(u8, ln, ';');
            const cps = std.mem.trim(u8, f.next().?, " ");
            const dots = std.mem.indexOf(u8, cps, "..");
            const lo = std.fmt.parseInt(u21, if (dots) |d| cps[0..d] else cps, 16) catch unreachable;
            const hi = if (dots) |d| std.fmt.parseInt(u21, cps[d + 2 ..], 16) catch unreachable else lo;
            var e: Entry = .{ .lo = lo, .hi = hi, .fields = .{ "", "" } };
            for (&e.fields) |*field| field.* = std.mem.trim(u8, f.next() orelse "", " ");
            return e;
        }
        return null;
    }
};

fn emit(w: *std.Io.Writer, comptime name: []const u8, comptime T: type, values: []const T) !void {
    try w.print("pub const {s}_start = [_]u21{{", .{name});
    for (values, 0..) |v, cp| if (cp == 0 or v != values[cp - 1]) try w.print("0x{X},", .{cp});
    try w.print("}};\npub const {s}_value = [_]{s}{{", .{ name, @typeName(T) });
    for (values, 0..) |v, cp| if (cp == 0 or v != values[cp - 1]) try w.print("{d},", .{v});
    try w.writeAll("};\n");
}
