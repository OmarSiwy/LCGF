#!/usr/bin/env python3
"""Generate optional typography properties from pinned Unicode 16 UCD (no host database).

Usage: python make_style.py /path/to/UCD
Data license: https://www.unicode.org/license.txt (Unicode License v3).
The punctuation exceptions follow CSS Text Decoration 3, text-emphasis-style.
"""
from pathlib import Path
import sys

ucd = Path(sys.argv[1])
category = ["Cn"] * 0x110000
decomposition = {}
pending = None
for line in (ucd / "UnicodeData.txt").read_text().splitlines():
    fields = line.split(";")
    cp = int(fields[0], 16)
    if fields[1].endswith(", First>"):
        pending = cp
    elif fields[1].endswith(", Last>"):
        for value in range(pending, cp + 1):
            category[value] = fields[2]
        pending = None
    else:
        category[cp] = fields[2]
    mapped = [int(value, 16) for value in fields[5].split() if not value.startswith("<")]
    if mapped:
        decomposition[cp] = mapped

exceptions = {0x23, 0x25, 0x2030, 0x2031, 0x66A, 0x609, 0x60A, 0x26, 0x204A,
              0x40, 0xA7, 0xB6, 0x204B, 0x2053, 0x303D}
def has_exception(cp):
    return cp in exceptions or any(has_exception(value) for value in decomposition.get(cp, ()))

flags = bytearray(0x110000)
for cp, name in enumerate(category):
    if name[0] == "Z":
        flags[cp] |= 2  # separator; a following combining mark restores emphasis
    elif name in ("Cc", "Cf", "Cn") or (name[0] == "P" and not has_exception(cp)):
        flags[cp] |= 4  # no emphasis
for line in (ucd / "EastAsianWidth.txt").read_text().splitlines():
    fields = line.partition("#")[0].strip().split(";")
    if len(fields) < 2 or fields[1].strip() not in ("A", "F", "W"):
        continue
    span = fields[0].strip().split("..")
    for cp in range(int(span[0], 16), int(span[-1], 16) + 1):
        flags[cp] |= 1 if fields[1].strip() == "A" else 8

ranges = []
for cp, value in enumerate(flags):
    if value == 0:
        continue
    if ranges and ranges[-1][1] + 1 == cp and ranges[-1][2] == value:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, value])
lines = ["//! Generated by make_style.py from Unicode 16.0.0; do not edit.",
         "//! Copyright © 2024 Unicode, Inc. Distributed under the Unicode License v3.",
         "//! https://www.unicode.org/license.txt",
         "pub const Range = struct { first: u21, last: u21, flags: u8 };",
         "pub const ranges = [_]Range{"]
lines += ["    .{ .first = 0x%X, .last = 0x%X, .flags = %d }," % tuple(row) for row in ranges]
lines.append("};")
target = Path(__file__).with_name("style_data.zig")
target.write_text("\n".join(lines) + "\n")
print(f"{len(ranges)} optional style-property ranges; {target}")
