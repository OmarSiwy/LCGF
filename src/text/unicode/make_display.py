#!/usr/bin/env python3
"""Regenerate optional display tables from the project's pinned Unicode 16 UCD.

Usage: python make_display.py /path/to/UCD
Unicode data: https://www.unicode.org/license.txt (Unicode License v3).
The source UCD version is intentionally the same as core segmentation and bidi.
"""
from pathlib import Path
import sys

ucd = Path(sys.argv[1])
maps = {}
wide = []
ccc = {}
for line in (ucd / "UnicodeData.txt").read_text().splitlines():
    f = line.split(";")
    cp = int(f[0], 16)
    value = [tuple(int(x, 16) for x in f[k].split()) or (cp,) for k in (13, 14, 12)]
    if not f[14]:
        value[1] = value[2]
    if any(x != (cp,) for x in value):
        maps[cp] = value
    if int(f[3]):
        ccc[cp] = int(f[3])
    if f[5].startswith("<narrow> "):
        wide.append((cp, int(f[5].split()[1], 16)))
for line in (ucd / "SpecialCasing.txt").read_text().splitlines():
    f = line.partition("#")[0].strip().split(";")
    if len(f) < 5 or f[4].strip():
        continue
    cp = int(f[0], 16)
    maps[cp] = [tuple(int(x, 16) for x in v.split()) for v in f[1:4]]

def properties(name, selected):
    out = {}
    for line in (ucd / name).read_text().splitlines():
        f = line.partition("#")[0].strip().split(";")
        if len(f) < 2 or f[1].strip() not in selected:
            continue
        span = f[0].strip().split("..")
        for cp in range(int(span[0], 16), int(span[-1], 16) + 1):
            out[cp] = out.get(cp, 0) | selected[f[1].strip()]
    return out

flags = properties("DerivedCoreProperties.txt", {"Cased": 1, "Case_Ignorable": 2})
for cp, value in properties("PropList.txt", {"Soft_Dotted": 4}).items():
    flags[cp] = flags.get(cp, 0) | value
vertical = properties("VerticalOrientation.txt", {"U": 1, "Tu": 2, "Tr": 3})

def ranges(values):
    result = []
    for cp, value in sorted(values.items()):
        if result and result[-1][1] + 1 == cp and result[-1][2] == value:
            result[-1][1] = cp
        else:
            result.append([cp, cp, value])
    return result

pool = []
offsets = {}
def encode(cp, mapped):
    if mapped == (cp,):
        return 0
    if mapped not in offsets:
        offsets[mapped] = len(pool)
        pool.extend(mapped)
    assert len(mapped) <= 3 and len(pool) < 16384
    return (offsets[mapped] << 2) | len(mapped)

lines = ["//! Generated by make_display.py from Unicode 16.0.0; do not edit.",
         "//! Copyright © 2024 Unicode, Inc. Distributed under the Unicode License v3.",
         "//! https://www.unicode.org/license.txt",
         "pub const Mapping = struct { cp: u21, modes: [3]u16 };",
         "pub const mappings = [_]Mapping{"]
for cp, value in sorted(maps.items()):
    codes = [encode(cp, v) for v in value]
    lines.append("    .{ .cp = 0x%X, .modes = .{ %s } }," % (cp, ", ".join(map(str, codes))))
lines += ["};", "pub const pool = [_]u21{"]
for start in range(0, len(pool), 12):
    lines.append("    " + ", ".join("0x%X" % cp for cp in pool[start:start+12]) + ",")
lines += ["};", "pub const Range = struct { first: u21, last: u21, value: u8 };"]
for name, values in (("flags", flags), ("combining", ccc), ("vertical", vertical)):
    lines.append("pub const %s = [_]Range{" % name)
    lines += ["    .{ .first = 0x%X, .last = 0x%X, .value = %d }," % tuple(r) for r in ranges(values)]
    lines.append("};")
lines += ["pub const Wide = struct { from: u21, to: u21 };", "pub const wide = [_]Wide{"]
lines += ["    .{ .from = 0x%X, .to = 0x%X }," % pair for pair in wide]
lines.append("};")
target = Path(__file__).with_name("display_data.zig")
target.write_text("\n".join(lines) + "\n")
print(f"{len(maps)} mappings, {len(pool)} expansion scalars; {target}")
