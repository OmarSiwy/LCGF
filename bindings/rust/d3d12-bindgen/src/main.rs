//! Generates lcgf's Direct3D 12 bindings (see Cargo.toml). `src/names.txt` lists what lcgf::gpu
//! calls and what those methods take; a method whose types are missing from it is skipped (and
//! reported here), so the list grows with the projection.
fn main() {
    let out = std::env::args()
        .nth(1)
        .expect("usage: d3d12-bindgen <out.rs>");
    let names: Vec<&str> = include_str!("names.txt").split_whitespace().collect();
    let mut args = vec![
        "--out",
        &out,
        "--flat",
        "--no-comment",
        "--no-allow",
        "--filter",
    ];
    args.extend(names.iter().copied());
    let warnings = windows_bindgen::bindgen(args).to_string();
    if !warnings.trim().is_empty() {
        eprintln!("{warnings}");
        std::process::exit(1);
    }
    // windows-core builds its string types only for Windows: the two the structs hold are the
    // parent module's, so the bindings build on Linux too (bindings/check's recorder).
    let code = std::fs::read_to_string(&out).unwrap();
    let mut code = code
        .replace("windows_core::PCWSTR", "super::PCWSTR")
        .replace("windows_core::PCSTR", "super::PCSTR");
    // Nor its `Free` (CloseHandle) for handles: the projection never owns a HANDLE.
    if let Some(at) = code.find("impl windows_core::Free for HANDLE {") {
        let end = at + code[at..].find("\n}\n").unwrap() + 3;
        code.replace_range(at..end, "");
    }
    let header = "// Generated by bindings/rust/d3d12-bindgen (windows-bindgen 0.65) from Microsoft's Win32\n\
                  // metadata. Do not edit: add names to its src/names.txt and run it again.\n";
    std::fs::write(&out, format!("{header}{code}")).unwrap();
}
